create policy staff_read_services      on public.services      for select to authenticated using ((select private.is_staff()));
create policy staff_read_documents     on public.documents     for select to authenticated using ((select private.is_staff()));
create policy staff_read_conversations on public.conversations for select to authenticated using ((select private.is_staff()));
create policy staff_read_messages      on public.messages      for select to authenticated using ((select private.is_staff()));
create policy staff_read_requests      on public.requests      for select to authenticated using ((select private.is_staff()));
create policy staff_update_requests    on public.requests      for update to authenticated
  using ((select private.is_staff())) with check ((select private.is_staff()));
create policy staff_read_interactions  on public.interactions  for select to authenticated using ((select private.is_staff()));
create policy staff_read_eval_runs     on public.eval_runs     for select to authenticated using ((select private.is_staff()));
create policy staff_read_eval_results  on public.eval_results  for select to authenticated using ((select private.is_staff()));
