-- Innova Copilot — initial schema (paso-02-arquitectura-datos)
-- Catalog + RAG storage, conversations, pre-proposals (requests), telemetry,
-- evals and rate limiting. RLS is enabled on every table: the public (anon)
-- role has NO direct access; the Next.js server uses the service role, and
-- staff (allowlisted emails) can read through RLS policies in /panel.

create extension if not exists vector with schema extensions;

create schema if not exists private;

-- ---------------------------------------------------------------------------
-- Catalog
-- ---------------------------------------------------------------------------
create table public.services (
  id text primary key,                       -- slug, e.g. 'simulacion-operaciones'
  name text not null,
  line text not null check (line in ('quality_assurance', 'business_innovation', 'process_design')),
  summary text not null,
  price_min_cop bigint not null check (price_min_cop >= 0),
  price_max_cop bigint not null check (price_max_cop >= price_min_cop),
  duration text not null,
  source_path text not null unique,          -- data/catalog/<file>.md
  updated_at timestamptz not null default now()
);

create table public.documents (
  id bigint generated always as identity primary key,
  source_path text not null unique,
  title text not null,
  kind text not null check (kind in ('service', 'policy')),
  service_id text references public.services (id) on delete set null,
  content text not null,
  checksum text not null,                    -- sha256 of content, to skip unchanged files on ingest
  updated_at timestamptz not null default now()
);
create index documents_service_id_idx on public.documents (service_id);

create table public.chunks (
  id bigint generated always as identity primary key,
  document_id bigint not null references public.documents (id) on delete cascade,
  chunk_index int not null,
  heading text,
  content text not null,
  embedding extensions.vector(1024),         -- voyage-3.5-lite; null when no VOYAGE_API_KEY
  fts tsvector generated always as (
    to_tsvector('spanish', coalesce(heading, '') || ' ' || content)
  ) stored,
  unique (document_id, chunk_index)
);
create index chunks_embedding_hnsw_idx on public.chunks
  using hnsw (embedding extensions.vector_cosine_ops);
create index chunks_fts_gin_idx on public.chunks using gin (fts);

-- ---------------------------------------------------------------------------
-- Conversations and pre-proposals
-- ---------------------------------------------------------------------------
create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  session_id text not null,
  ip_hash text,                              -- sha256(ip + salt); never the raw IP
  prompt_version text,
  line text check (line in ('quality_assurance', 'business_innovation', 'process_design')),
  message_count int not null default 0,
  has_proposal boolean not null default false,
  is_synthetic boolean not null default false, -- traffic generated by scripts/simulate-traffic.ts
  started_at timestamptz not null default now(),
  last_message_at timestamptz not null default now()
);
create index conversations_started_at_idx on public.conversations (started_at desc);

create table public.messages (
  id bigint generated always as identity primary key,
  conversation_id uuid not null references public.conversations (id) on delete cascade,
  role text not null check (role in ('user', 'assistant', 'tool')),
  content jsonb not null,
  created_at timestamptz not null default now()
);
create index messages_conversation_id_idx on public.messages (conversation_id, created_at);

create table public.requests (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid references public.conversations (id) on delete set null,
  company text not null,
  contact_name text not null,
  contact_email text,
  line text not null check (line in ('quality_assurance', 'business_innovation', 'process_design')),
  problem_summary text not null,
  recommended_services text[] not null default '{}',
  scope text not null,
  investment_range_cop text not null,
  status text not null default 'new' check (status in ('new', 'in_review', 'proposal_sent', 'closed')),
  is_demo_seed boolean not null default false, -- fictional seed data
  created_at timestamptz not null default now()
);
create index requests_conversation_id_idx on public.requests (conversation_id);
create index requests_line_status_idx on public.requests (line, status, created_at desc);

-- ---------------------------------------------------------------------------
-- Telemetry (one row per assistant turn)
-- ---------------------------------------------------------------------------
create table public.interactions (
  id bigint generated always as identity primary key,
  conversation_id uuid references public.conversations (id) on delete cascade,
  created_at timestamptz not null default now(),
  mode text not null check (mode in ('live', 'mock')),
  model text not null,
  prompt_version text not null,
  input_tokens int not null default 0,
  output_tokens int not null default 0,
  cache_read_tokens int not null default 0,
  cache_write_tokens int not null default 0,
  cost_usd numeric(12, 6) not null default 0,
  latency_ms int,                            -- full turn
  ttft_ms int,                               -- time to first token
  tools_used text[] not null default '{}',
  error text,
  is_synthetic boolean not null default false
);
create index interactions_conversation_id_idx on public.interactions (conversation_id);
create index interactions_created_at_idx on public.interactions (created_at desc);

-- ---------------------------------------------------------------------------
-- Evals
