create table public.eval_results (
  id bigint generated always as identity primary key,
  run_id uuid not null references public.eval_runs (id) on delete cascade,
  case_id text not null,
  passed boolean not null,
  checks jsonb not null,                     -- deterministic checks
  judge jsonb,                               -- LLM-as-judge scores
  output text,
  tool_calls jsonb,
  latency_ms int,
  cost_usd numeric(12, 6)
);
create index eval_results_run_id_idx on public.eval_results (run_id);

-- ---------------------------------------------------------------------------
-- Rate limiting (fixed windows) and staff allowlist
-- ---------------------------------------------------------------------------
create table public.rate_limits (
  key text not null,                         -- 'ip:<hash>', 'session:<id>', 'daily:conversations'
  window_start timestamptz not null,
  count int not null default 0,
  primary key (key, window_start)
);

create table private.staff_allowlist (
  email text primary key check (email = lower(email))
);

-- Atomically count a hit and report whether it is still within the limit.
-- Called only by the server (service role).
create or replace function public.hit_rate_limit(p_key text, p_window_seconds int, p_max int)
returns table (allowed boolean, current_count int, reset_at timestamptz)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_window timestamptz := to_timestamp(floor(extract(epoch from now()) / p_window_seconds) * p_window_seconds);
  v_count int;
begin
  insert into public.rate_limits as rl (key, window_start, count)
  values (p_key, v_window, 1)
  on conflict (key, window_start) do update set count = rl.count + 1
  returning rl.count into v_count;

  return query select v_count <= p_max, v_count, v_window + make_interval(secs => p_window_seconds);
end;
$$;
revoke execute on function public.hit_rate_limit(text, int, int) from public, anon, authenticated;
grant execute on function public.hit_rate_limit(text, int, int) to service_role;

-- True when the logged-in user's email is on the staff allowlist.
create or replace function private.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from private.staff_allowlist
    where email = lower((select auth.jwt() ->> 'email'))
  );
$$;
revoke execute on function private.is_staff() from public, anon;
grant usage on schema private to authenticated;
grant execute on function private.is_staff() to authenticated;

